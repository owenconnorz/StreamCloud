#!/usr/bin/env python3
"""Bundle Google's Rounded Symbols as Compose vectors; never rewrite app screens."""
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
from pathlib import Path
import re
import ssl
import urllib.request
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "app/src/main/java"
OUTPUT = SOURCE / "com/streamcloud/app/ui/icons"
ASSETS = ROOT / "app/src/main/assets/licenses"
MANIFEST = OUTPUT / "material-symbols-manifest.json"
REPOSITORY = "https://raw.githubusercontent.com/google/material-design-icons"
ALIASES = {
    "BookmarkBorder": ("bookmark", False),
    "FavoriteBorder": ("favorite", False),
    "ErrorOutline": ("error", False),
    "NotificationsNone": ("notifications", False),
    "Collections": ("photo_library", None),
    "OndemandVideo": ("smart_display", None),
    "Restore": ("history", None),
    "Whatshot": ("local_fire_department", None),
    "SignalWifiStatusbarConnectedNoInternet4": ("signal_wifi_statusbar_not_connected", None),
}
MIRRORED = {"arrow_back", "arrow_forward", "compare_arrows", "playlist_add", "playlist_play", "send"}


def download(url):
    request = urllib.request.Request(url, headers={"User-Agent": "StreamCloud-icon-generator"})
    with urllib.request.urlopen(request, timeout=45, context=ssl.create_default_context()) as response:
        return response.read()


def snake(name):
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    return re.sub(r"([A-Za-z])([0-9])", r"\1_\2", name).lower()


def kotlin_string(value):
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$")


def generate(commit):
    names = set()
    for path in SOURCE.rglob("*.kt"):
        names.update(re.findall(r"\bIcons\.(?:AutoMirrored\.)?(?:Default|Filled|Outlined|Rounded)\.(\w+)", path.read_text()))
    if not names:
        raise RuntimeError("No app icon references found")
    mapping = {name: ALIASES.get(name, (snake(name), None)) for name in sorted(names)}
    symbols = sorted({value[0] for value in mapping.values()})
    cache = Path("/tmp/streamcloud-material-symbols") / commit
    cache.mkdir(parents=True, exist_ok=True)

    def asset(key):
        symbol, filled = key
        filename = f"{symbol}{'_fill1' if filled else ''}_24px.svg"
        url = f"{REPOSITORY}/{commit}/symbols/web/{symbol}/materialsymbolsrounded/{filename}"
        target = cache / filename
        raw = target.read_bytes() if target.exists() else download(url)
        xml = ET.fromstring(raw)
        view_box = [float(value) for value in xml.attrib.get(
            "viewBox", f"0 0 {xml.attrib['width']} {xml.attrib['height']}",
        ).split()]
        if len(view_box) != 4 or min(view_box[2:]) <= 0:
            raise RuntimeError(f"Unsupported viewBox: {filename}")
        paths = []
        for child in xml:
            if child.tag.rsplit("}", 1)[-1] != "path" or set(child.attrib) - {"d"}:
                raise RuntimeError(f"Unsupported SVG node: {filename}")
            paths.append(child.attrib["d"])
        if not paths:
            raise RuntimeError(f"Empty symbol: {filename}")
        target.write_bytes(raw)
        return {
            "key": f"{symbol}:{int(filled)}", "symbol": symbol, "filled": filled,
            "paths": paths, "sha256": hashlib.sha256(raw).hexdigest(), "url": url,
            "view_box": view_box,
        }

    keys = [(symbol, filled) for symbol in symbols for filled in (False, True)]
    with ThreadPoolExecutor(max_workers=10) as pool:
        vectors = list(pool.map(asset, keys))
    OUTPUT.mkdir(parents=True, exist_ok=True)
    ASSETS.mkdir(parents=True, exist_ok=True)
    header = (
        "// Generated by scripts/generate-material-symbols.py. Do not hand-edit.\n"
        "// Google Material Symbols Rounded, Apache-2.0; see bundled license.\n"
        f"// Upstream revision: {commit}\n"
        "package com.streamcloud.app.ui.icons\n\n"
    )
    for part, start in enumerate(range(0, len(vectors), 50), 1):
        text = header + f"internal object RoundedSymbolPaths{part} {{\n"
        for item in vectors[start:start + 50]:
            text += f"    val {item['symbol']}_{int(item['filled'])} = RoundedSymbolData(listOf("
            text += ", ".join(kotlin_string(path) for path in item["paths"]) + ")"
            if item["view_box"] != [0, -960, 960, 960]:
                text += ", " + ", ".join(f"{value:g}f" for value in item["view_box"])
            text += ")\n"
        text += "}\n"
        (OUTPUT / f"RoundedSymbolPaths{part}.kt").write_text(text)
    catalog = header + "internal fun roundedSymbolData(key: String): RoundedSymbolData = when (key) {\n"
    for index, item in enumerate(vectors):
        catalog += f'    "{item["key"]}" -> RoundedSymbolPaths{index // 50 + 1}.{item["symbol"]}_{int(item["filled"])}\n'
    catalog += '    else -> error("Unbundled Material Symbol: $key")\n}\n'
    (OUTPUT / "RoundedSymbolCatalog.kt").write_text(catalog)
    icons = header + "import androidx.compose.ui.graphics.vector.ImageVector\n\n"
    icons += "/** Local Rounded Symbols. Border aliases retain their existing toggle meanings. */\n"
    icons += "object AppIcons {\n    val Default get() = Filled\n    val Rounded get() = Filled\n"
    for style, default in (("Filled", True), ("Outlined", False)):
        icons += f"    object {style} {{\n"
        for name, (symbol, fixed) in mapping.items():
            filled = default if fixed is None else fixed
            icons += f'        val {name}: ImageVector get() = roundedMaterialSymbol("{symbol}", {str(filled).lower()})\n'
        icons += "    }\n"
    icons += "    object AutoMirrored {\n        val Filled get() = AppIcons.Filled\n        val Outlined get() = AppIcons.Outlined\n    }\n}\n"
    (OUTPUT / "AppIcons.kt").write_text(icons)
    manifest = {
        "family": "Material Symbols Rounded", "weight": 400, "optical_size": 24,
        "upstream_commit": commit, "license": "Apache-2.0",
        "aliases": {name: {"symbol": symbol, "fixed_fill": filled} for name, (symbol, filled) in mapping.items()},
        "auto_mirrored": sorted(MIRRORED),
        "assets": [{k: v for k, v in item.items() if k != "paths"} for item in vectors],
    }
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n")
    license_bytes = download(f"{REPOSITORY}/{commit}/LICENSE")
    (ASSETS / "google-material-symbols-Apache-2.0.txt").write_bytes(license_bytes)
    (ASSETS / "google-material-symbols-NOTICE.txt").write_text(
        "Material Symbols Rounded\nCopyright Google LLC\n"
        "https://github.com/google/material-design-icons\nLicensed under Apache License 2.0.\n"
        f"Upstream revision: {commit}\n"
        "SVG artwork converted into offline Compose ImageVectors for StreamCloud.\n"
    )
    print(f"Bundled {len(names)} icon names, {len(vectors)} SVG variants at {commit}.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--revision", help="Upstream Git commit; defaults to the saved manifest revision")
    args = parser.parse_args()
    revision = args.revision
    if not revision and MANIFEST.exists():
        revision = json.loads(MANIFEST.read_text())["upstream_commit"]
    if not revision:
        revision = json.loads(download("https://api.github.com/repos/google/material-design-icons/commits/master"))["sha"]
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise SystemExit("Use a full upstream commit SHA")
    generate(revision)
